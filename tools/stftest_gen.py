#!/usr/bin/env python3
"""stftest_gen.py - turn a tools/cop_ext_gen.py script and its host-model results into
src/stftest_cases.h for src/stftest.c.

  stftest_gen.py t1.txt h1.txt > src/stftest_cases.h

Each case: command number, argument count, result count (from the host run), arguments.
`buf` lines go to stf_bufs (buffer RAM word, count, words; a count of 0 ends it).
`mat` lines become command 0x04 (load the matrix) with no results.
"""
import sys

cases, bufs, nout = [], [], 0
res = [l.split("|")[0].split(":")[1].split() for l in open(sys.argv[2]) if ":" in l]
k = 0
for line in open(sys.argv[1]):
    t = line.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "buf":
        bufs.append((int(t[1], 16), t[2:]))
        continue
    if t[0] == "mat":
        cases.append((4, t[1:], 0))
        continue
    cases.append((int(t[0], 16), t[1:], len(res[k])))
    k += 1
assert k == len(res), (k, len(res))
print("/* Generated by tools/stftest_gen.py from %s - do not edit. */" % sys.argv[1].rsplit("/", 1)[-1])
print("#define STF_NCASES %d" % len(cases))
print("#define STF_NOUT %d     /* result words, plus 12 matrix words per case */" % sum(c[2] for c in cases))
print("static const u32 stf_bufs[] = {")
for w, a in bufs:
    print("    0x%04x, %d,%s" % (w, len(a), "".join(" 0x%s," % v for v in a)))
print("    0, 0,")
print("};")
print("static const u32 stf_cases[] = {")
for n, a, o in cases:
    print("    0x%02x, %d, %d,%s" % (n, len(a), o, "".join(" 0x%su," % w for w in a)))
print("};")
