#!/usr/bin/env python3
"""vaporbench_gen.py - pick one case per cpres1 command out of src/stftest_cases.h for
src/vaporbench.c's every-command benchmark, and write src/vaporbench_cases.h.

  python3 tools/vaporbench_gen.py src/stftest_cases.h > src/vaporbench_cases.h

The commands the 2A/2C kernels run natively are left out: vaporbench times those itself, with
arguments it checks. For each other command the first case stftest has is kept (its arguments
and its result count), so every command gets arguments that ran on all three boards.

stftest puts the buffer RAM words its cases read at words 0x3800 (0x67-0x69's matrices) and
0x3900 (0x4a's osage records). vaporbench draws while it benchmarks, and with M2_COP_EXT on 2A/2C
its display lists live in words 0x0000-0x3fff, so the words move to the end of the last list
buffer (VB_BUF_BASE), which a list of up to 0xe00 words never reaches; the offset arguments move
with them.
"""
import re, sys

NATIVE = {1, 2, 3, 5, 6, 7, 8, 9, 10, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x1a, 0x21, 0x22, 0x23,
          0x24, 0x25, 0x2b, 0x2c, 0x2d, 0x2f, 0x59, 0x5c, 0x5d, 0x5e, 0x78}
OLD_MAT, OLD_OSAGE = 0x3800, 0x3900
NEW_MAT, NEW_OSAGE = 0x3e00, 0x3f00

src = open(sys.argv[1]).read()
def array(name):
    body = re.search(r"%s\[\] = \{(.*?)\};" % name, src, re.S).group(1)
    return [int(w.rstrip("u"), 16 if "0x" in w else 10) for w in re.findall(r"0x[0-9a-fA-F]+u?|\b\d+\b", body)]

bufs, cases = array("stf_bufs"), array("stf_cases")
moved = {OLD_MAT: NEW_MAT, OLD_OSAGE: NEW_OSAGE}
blocks, i = [], 0
while bufs[i + 1]:
    blocks.append((moved[bufs[i]], bufs[i + 2:i + 2 + bufs[i + 1]]))
    i += 2 + bufs[i + 1]
assert NEW_MAT + len(blocks[0][1]) <= NEW_OSAGE and NEW_OSAGE + len(blocks[1][1]) <= 0x4000

seen, picked, i = set(), [], 0
while i < len(cases):
    n, na, nr = cases[i:i + 3]
    a = cases[i + 3:i + 3 + na]
    i += 3 + na
    if n in NATIVE or n in seen:
        continue
    seen.add(n)
    a = list(a)
    if n in (0x67, 0x68, 0x69):
        assert OLD_MAT <= a[0] < OLD_OSAGE
        a[0] += NEW_MAT - OLD_MAT
    if n == 0x4a:
        assert a[0] == OLD_OSAGE
        a[0] = NEW_OSAGE
    picked.append((n, nr, a))

print("/* Generated by tools/vaporbench_gen.py from %s - do not edit. */" % sys.argv[1].rsplit("/", 1)[-1])
print("#define VB_NEXT %d        /* commands */" % len(picked))
print("#define VB_BUF_BASE 0x%04xu" % NEW_MAT)
print("static const u32 vb_bufs[] = {")
for w, a in blocks:
    print("    0x%04x, %d,%s" % (w, len(a), "".join(" 0x%08x," % v for v in a)))
print("    0, 0,")
print("};")
print("/* per command: number, argument count, result count, arguments */")
print("static const u32 vb_cases[] = {")
for n, nr, a in picked:
    print("    0x%02x, %d, %d,%s" % (n, len(a), nr, "".join(" 0x%08xu," % w for w in a)))
print("};")
